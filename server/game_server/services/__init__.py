"""业务层：与 HTTP 协议无关的游戏逻辑。

- ``base``          请求上下文（会话 / 角色）与带 Global 的回复类型
- ``clock``         服务器时间：游戏日、月份、倒计时（测试可冻结）
- ``account``       账号、票据、会话
- ``hero_model``    英雄属性、战力、经验曲线、进阶规则（客户端不计算任何属性）
- ``equipment``     法宝实例模型：创建、属性、锻造费用、碎片
- ``player_state``  角色状态：初始状态、迁移、每日重置、体力恢复、投影、Notify
- ``inventory``     账本（全部 ItemType 的奖励/消耗结算）、道具使用、商店、神秘商店
- ``battle``        战斗引擎：NPC 表阵容、多波次、怒气技、战报
- ``stages``        关卡：多波次结算、扫荡、章节宝箱、新手引导
- ``team``          阵容、小伙伴、图鉴
- ``growth``        英雄成长：经验池升级、进阶、培养、将魂招募、技能训练
- ``talisman``      法宝接口：锻造、重铸、喂灵、合成、分解、穿卸
- ``recruitment``   招募：卡池、免费冷却、十连、保底、新手首抽
- ``mail``          邮件
- ``activities``    签到、征收、七日登录、等级礼包、月卡、跑马灯
- ``missions``      任务系统与进度事件
- ``pvp``           争霸（机器人排行榜）、妖王洞穴（本地活动时段）
- ``dungeons``      十二元辰殿、通天塔
- ``social``        炼化炉、好友（机器人）、运镖
- ``roles``         角色仓储与创建 / 加载

处理函数签名统一为 ``handler(ctx, params)``：``ctx`` 是 ``SessionContext`` 或 ``RoleContext``，
``params`` 是协议层已校验的业务参数。公开接口（无需会话）签名为 ``handler(params)``。
"""
